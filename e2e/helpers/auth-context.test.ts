import { mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { describe, expect, it } from "vitest";

import { assertDevCertHashesPresent, readDevCertHashes } from "./auth-context";

/**
 * Regression lock for #2159's second half: a missing hash file was swallowed
 * silently, and nothing downstream turned that into an actionable message. The
 * silence is the defect — an empty array makes CERT_HASH_INIT_SCRIPT a no-op and
 * the handshake fails later as QUIC_TLS_CERTIFICATE_UNKNOWN, which reads
 * like a broken server. Now that the file is gitignored, a fresh clone hits this
 * on its first WT run.
 */
describe("readDevCertHashes", () => {
  const dir = mkdtempSync(join(tmpdir(), "vc-cert-hash-"));

  it("returns an empty array when the file is absent", () => {
    // Must not throw at module-import time: every spec imports auth-context,
    // including the WS-only majority that never needs the hash.
    expect(readDevCertHashes(join(dir, "does-not-exist.txt"))).toEqual([]);
  });

  it("strips the comment preamble and blank lines the generator writes", () => {
    // `regen-dev-cert.sh` writes a human-readable header above the digest. A
    // comment line reaching the wasm side would be injected as a bogus hash.
    const p = join(dir, "with-preamble.txt");
    writeFileSync(
      p,
      ["# Generated by scripts/regen-dev-cert.sh", "# do not edit", "", "  AAAA=  ", ""].join("\n"),
    );
    expect(readDevCertHashes(p)).toEqual(["AAAA="]);
  });
});

describe("assertDevCertHashesPresent", () => {
  it("throws an actionable error naming the remedy when no hash is present", () => {
    // The whole point of the change: name the command that fixes it, matching
    // the diagnostic `regen-dev-cert.sh` already prints.
    expect(() => assertDevCertHashesPresent([])).toThrow(/make e2e-cert/);
    // And explain WHY it is absent, since a fresh clone legitimately has no hash
    // now that the file is gitignored.
    expect(() => assertDevCertHashesPresent([])).toThrow(/#2159/);
  });

  it("does not throw when a hash is present", () => {
    expect(() => assertDevCertHashesPresent(["AAAA="])).not.toThrow();
  });
});
