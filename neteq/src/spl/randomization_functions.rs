/// C `IncreaseSeed` (file-static in C): `seed = (seed * 69069 + 1) & 0x7fffffff`.
/// The `(int32_t)69069` converts to `uint32_t`, so the product wraps mod 2^32.
pub fn increase_seed(seed: &mut u32) -> u32 {
    *seed = (seed.wrapping_mul(69069).wrapping_add(1)) & (MAX_SEED_USED - 1);
    *seed
}

/// C `WebRtcSpl_RandU`: uniform in `[0, 32767]`.
pub fn rand_u(seed: &mut u32) -> i16 {
    (increase_seed(seed) >> 16) as i16
}

/// C `WebRtcSpl_RandN`: Gaussian, from `kRandNTable`.
pub fn rand_n(seed: &mut u32) -> i16 {
    RAND_N_TABLE[(increase_seed(seed) >> 23) as usize]
}

/// C `WebRtcSpl_RandUArray`. Returns `vector_length`.
pub fn rand_u_array(vector: &mut [i16], vector_length: i16, seed: &mut u32) -> i16 {
    for value in &mut vector[..vector_length.max(0) as usize] {
        *value = rand_u(seed);
    }
    vector_length
}

#[cfg(test)]
mod tests {
    use super::*;

    // signal_processing_unittest.cc: SplTest.RandTest
    #[test]
    fn rand_test() {
        let bu: [i16; 4] = [3653, 12446, 8525, 30691];
        let mut b16 = [0i16; 4];
        let mut seed: u32 = 100000;
        assert_eq!(7086, rand_u(&mut seed));
        assert_eq!(31565, rand_u(&mut seed));
        assert_eq!(-9786, rand_n(&mut seed));
        assert_eq!(4, rand_u_array(&mut b16, 4, &mut seed));
        assert_eq!(bu, b16);
    }
}
